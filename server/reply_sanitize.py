"""Санитайзер профанизма итогового reply (задача 21).

ЗАЧЕМ: uncensored-модель иногда вставляет мат в финальную реплику
(живой факт: «...Назови товары и количество, блядь.»), промптовые
правила её не удерживают. Точки применения: ЕДИНАЯ точка на общем
пути answer._answer -- REST /ask + /voice, история (add_turn) и
/ws_voice (voice_ws берёт оттуда resp.reply для TTS) -- плюс ЯВНЫЕ
точки во ВСЕХ reply-сборках POST /confirm (server.py: модель, веб-
суммаризация поиска, ошибки, статические строки). Пользовательские
данные (args/items) и шаблоны dispatch не санитайзятся.

СТЕМ-ЛИСТ (закрытый, консервативный; заменяются ЦЕЛИКОМ только те
слова, которые НАЧИНАЮТСЯ с однозначного матёрного стёма и до конца
слова не несут нейтрального значения):

* бля/бляд-/бля+   бля, блядь, бляди, блядский... + растяжки гласными
                («бляяя», «бляааа», «бляю»); после «д» допускается
                любой хвост; совпадение обязано ЗАКАНЧИВАТЬСЯ словом,
                поэтому нейтральные «бляха», «блашка», «благовест»,
                «блажь» НЕ задеваются;
* ху(й|я|е|ё|и)- хуй/хуя/хуё/хуе/хуи + любой хвост (хуесос, хуйня...);
* еб-/ёб-       ебать, ёбнулся... + хвост; только слово-начало, поэтому
                «небольшой» (еб внутри слова) НЕ задевается;
* пизд-        пиздец, пиздеть и т.п. + хвост;
* манд-        ТОЛЬКО короткие падежи (манда/манду/мандой/мандам...):
                «мандат», «мандарин» НЕ задеваются;
* хер-         хер/хера/хером/херня/херный и т.п.; одиночная «-и-»
                («херить») и «-у-» («херувим») сознательно НЕ включены.

ВНЕ границ: приставочный мат («наебать», «охуеть», «въебать») НЕ
вырезается -- по ТЗ граница только слева (?<![а-яёА-ЯЁ]); вырезать
внутри слов нельзя без ложных срабатываний (см. примеры выше).
«\\b» в Python на кириллице границей слова НЕ является, поэтому
используется явная кириллическая граница.

Санитайзер ИДЕМПОТЕНТЕН: чистый текст не меняется.
"""
import re

# Скользкая часть -- сам стем-лист; читай комментарии рядом с ветками.
# Левая граница (?<![а-яёА-ЯЁ]): стём должен НАЧИНАТЬ слово (или стоять
# после не-буквы); правая (?![а-яёА-ЯЁ]): совпадение должно ЗАКАНЧИВАТЬ
# слово -- нейтральные омонимы/ложные друзья «бляха», «мандат», «херувим»
# не проходят мимо этой проверки.
_WORD_RE = re.compile(r"""
    (?<![а-яёА-ЯЁ])
    (?: бля(?:д[а-яёА-ЯЁ]*|[яюиёа]+)?                   # бля/блядь/бляяя
      | ху[йяеёи][а-яёА-ЯЁ]*                            # хуй/хуя/хуе/хуё/хуи...
      | [её]б[а-яёА-ЯЁ]*                                # еб-/ёб- формы
      | пизд[а-яёА-ЯЁ]*                                 # пиздец/пиздеть...
      | манд(?:а|у|ы|е|ю|ой|ою|ам|ами|ах)?(?![а-яёА-ЯЁ]) # манд- падежи
      | хер(?:н[а-яёА-ЯЁ]*|ом|ем|ам|ами|ах|ов|а|ы|е|ь)?(?![а-яёА-ЯЁ])
    )
    (?![а-яёА-ЯЁ])
""", re.VERBOSE | re.IGNORECASE)


def _tidy(text: str) -> str:
    """Чистка после удаления слов: пробелы и провисшая пунктуация.

    Правила только для бита, который мог остаться после вырезания
    («, блядь.» -> «, .» -> «.»); корректный текст последний не меняет.
    """
    text = re.sub(r"\s+", " ", text)          # сдвоенные пробелы -> один
    text = re.sub(r"\s+([,.!?;:…])", r"\1", text)   # пробел ПЕРЕД знаком
    text = re.sub(r"([;:!])\s*,", r"\1", text)      # «доверяю: бля, ...»
    text = re.sub(r",\s*([.!?;:])", r"\1", text)    # «, бля.» -> «.»
    text = re.sub(r",\s*,", ",", text)              # «привет, бля, как»
    text = re.sub(r"^\s*[,;:.]+\s*", "", text)      # «, как дела?» в начале
    text = re.sub(r"\s*[,;:]*\s*$", "", text)       # «...и количество,» хвост
    return text.strip()


def sanitize_reply(text: str) -> str:
    """Убирает матёрные слова из реплики; идемпотентен (повторный вызов
    на чистом тексте возвращает его без изменений)."""
    if not text:
        return text
    return _tidy(_WORD_RE.sub("", text))
